#!/usr/bin/env python3
"""Generates core/lyrics/hanfold_table.go from the Unicode Han Database.

The table maps a traditional Chinese character to its simplified form, so that
"陳奕迅" and "陈奕迅" compare equal when lyrics results are matched with a track,
and so that Chinese services can be asked in the form they index.

Source: Unihan_Variants.txt (kSimplifiedVariant), from
https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
Unicode Data Files are provided under the Unicode License (see
https://www.unicode.org/license.txt); the generated file says so.

A character is mapped only when the first simplified variant Unicode gives is
another character. Characters whose first variant is themselves (乾, which may
stay 乾 or become 干) are left alone: guessing would change words.

Usage: python3 scripts/gen_hanfold.py Unihan_Variants.txt > core/lyrics/hanfold_table.go
"""
import re
import sys

version = "unknown"
pairs = {}
with open(sys.argv[1], encoding="utf-8") as f:
    for line in f:
        m = re.match(r"# Unicode Version (\S+)", line)
        if m:
            version = m.group(1)
        if line.startswith("#") or "\tkSimplifiedVariant\t" not in line:
            continue
        src, _, targets = line.rstrip("\n").split("\t")
        first = targets.split()[0]
        s, t = int(src[2:], 16), int(first[2:], 16)
        if s != t:
            pairs[s] = t

def lit(cp):
    # Go string literal: characters of the Basic Multilingual Plane as they are,
    # the others as \U escapes (a Go \x escape would be a byte, not a character)
    if cp < 0x10000 and chr(cp).isprintable() and chr(cp) not in '"\\':
        return chr(cp)
    return "\\U%08X" % cp

body = "".join(lit(s) + lit(pairs[s]) for s in sorted(pairs))
print(f"""// Code generated by scripts/gen_hanfold.py from Unihan_Variants.txt
// (Unicode {version}, kSimplifiedVariant); DO NOT EDIT.
//
// Unicode Data Files are © Unicode, Inc. and distributed under the Unicode
// License: https://www.unicode.org/license.txt

package lyrics

// hanSimplified holds {len(pairs)} pairs: each traditional character followed by
// its simplified form.
const hanSimplified = """ + '"' + body + '"')
